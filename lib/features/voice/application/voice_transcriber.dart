/// Adapts a local [File] to [UploadSource] for one upload, mirroring
/// `SafUploadSource`'s own thin forward — the local source here is never
/// SAF, just a plain temp file [RecordPluginVoiceRecorder] already wrote.
class _FileUploadSource implements UploadSource {
  _FileUploadSource(this._file);

  final File _file;

  @override
  Future<int> length() => _file.length();

  @override
  Stream<List<int>> openRead() => _file.openRead();
}

/// Uploads a finished [VoiceRecording] to the Mac and transcribes it with
/// `whisper-cli`, deleting both copies of the audio no matter how the
/// attempt ends.
///
/// Reuses the two seams this feature was told to reuse rather than
/// reinvent: [SftpUploadService] moves the bytes, [HostCommandRunner]
/// runs the remote command. Both are constructor parameters, not fields
/// this class builds for itself — the caller supplies a live SSH session,
/// exactly as [SftpUploadService] and every real [HostCommandRunner]
/// already require elsewhere in this app. See
/// `odd/tasks/voice-input-cross-platform.md`'s "What to build" for why
/// this class must not reach for a session of its own.
///
/// SECURITY, not decoration (S3 of that document):
/// - Every path that reaches the remote shell — the uploaded audio's
///   remote path and the model path — is wrapped in [shellQuote]. Both
///   are effectively attacker-influenced: a recording's filename is
///   generated by this app today, but the remote path it is uploaded
///   under is still a STRING built by string interpolation before it
///   ever reaches a shell, and treating it as untrusted costs nothing.
/// - The remote file is deleted in a `finally`, so a thrown transcription
///   command never leaves a recording of the owner's voice on the Mac.
/// - The local temp file is deleted on the same terms.
/// - NEVER LOG THE TRANSCRIPT. [_log] below only ever reports a LENGTH,
///   never the text — dictation can carry secrets and this app's
///   loggers print at info level, which `flutter run` shows in plain
///   text.
class VoiceTranscriber {
  VoiceTranscriber({
    required SftpUploadService uploadService,
    required HostCommandRunner hostRunner,
    String remoteDirectory = _defaultRemoteDirectory,
    String modelPath = _defaultModelPath,
  }) : _uploadService = uploadService,
       _hostRunner = hostRunner,
       _remoteDirectory = remoteDirectory,
       _modelPath = modelPath;

  static final _log = HelmLogger('VoiceTranscriber');

  final SftpUploadService _uploadService;
  final HostCommandRunner _hostRunner;
  final String _remoteDirectory;
  final String _modelPath;

  /// Where the recording lands before transcription, under the owner's
  /// own login — never a path this repository could leak a real
  /// deployment's layout through. `/tmp` is writable by the connecting
  /// user on every macOS install, so no per-owner configuration is
  /// needed for this to work out of the box.
  static const _defaultRemoteDirectory = '/tmp';

  /// `ggml-large-v3-turbo`, matching the measured numbers this feature's
  /// document carries over, at the location Homebrew's `whisper-cpp`
  /// downloads models to.
  ///
  /// MEASURED, and the reason this is not just the model's NAME: passing
  /// `-m ggml-large-v3-turbo` exits 3 with "failed to initialize whisper
  /// context". `whisper-cli` wants a path to the `.bin`, and resolves no
  /// names of its own. The unit tests cannot catch this — they run
  /// against a fake [HostCommandRunner] that never executes anything —
  /// so it was found by running the real binary both ways.
  ///
  /// Relative to `$HOME` rather than absolute, because a real home
  /// directory must not be committed to a public repository. See
  /// [_modelArgument] for how that survives shell quoting.
  static const _defaultModelPath = '.cache/whisper-cpp/ggml-large-v3-turbo.bin';

  /// The vocabulary prompt measured in `voice-and-share-input.md`: with it,
  /// `whisper-cli` ran FASTER (1.35s vs 1.92s on the same 5.3s clip) AND
  /// fixed two of the three terms it had mangled ("on-task removed" to
  /// "onTaskRemoved", "ELM" to "helm"). `repo` was missing from that run
  /// and stayed wrong — the reason this is a maintained constant rather
  /// than a one-off string: every term this mangles belongs here once
  /// noticed.
  ///
  /// No real hostname, tailnet name or personal path, per this feature's
  /// publicrepo constraint — every term below is either a generic
  /// programming word or this repository's own public name.
  static const vocabularyPrompt =
      'onTaskRemoved, dartssh2, helm, repo, SSH, SFTP, tmux, zellij, '
      'Flutter, Riverpod';

  /// Uploads [recording], runs `whisper-cli` against it, and returns the
  /// transcript — or why there is none. Deletes BOTH the remote and the
  /// local copy of the audio before returning, regardless of outcome.
  Future<VoiceTranscription> transcribe(VoiceRecording recording) async {
    final localFile = File(recording.path);
    // Built from the LOCAL recording's own basename, not a name this
    // class invents: [VoiceRecording.path] is the one piece of
    // caller-supplied data this method ever turns into a remote path, so
    // it is the thing [_transcribeCommand]'s shellQuote call exists to
    // defend, exactly as this feature's security requirement names it.
    final remotePath = '$_remoteDirectory/${_basename(recording.path)}';

    try {
      final outcome = await _uploadService.upload(
        _FileUploadSource(localFile),
        remotePath,
      );
      if (outcome is! UploadCompleted) {
        return VoiceTranscriptionFailed(
          'Upload did not complete: ${outcome.runtimeType}',
        );
      }

      try {
        final command = _transcribeCommand(outcome.path);
        final result = await _hostRunner.run(command);
        if (result.timedOut) {
          return const VoiceTranscriptionFailed(
            'Transcription command timed out',
          );
        }
        if (result.exitCode != null && result.exitCode != 0) {
          return VoiceTranscriptionFailed(
            'whisper-cli exited ${result.exitCode}',
          );
        }
        final text = result.stdout.trim();
        // Length only — see this class's comment on why the text itself
        // never reaches a log call.
        _log.i('Transcription produced ${text.length} characters');
        return VoiceTranscriptionSucceeded(text);
      } catch (error) {
        _log.w('whisper-cli failed: $error');
        return VoiceTranscriptionFailed('$error');
      } finally {
        // Deletes even when the `try` above threw: a recording of the
        // owner's voice must never survive a failed transcription on the
        // Mac. See this feature's S3 and the task's explicit requirement.
        await _deleteRemoteQuietly(outcome.path);
      }
    } finally {
      // Same guarantee, locally: this runs whether upload, transcription,
      // or neither failed.
      await _deleteLocalQuietly(localFile);
    }
  }

  /// The final path segment, matching `SftpUploadService._freePath`'s own
  /// manual split — no `package:path` dependency exists in this app, and
  /// a whole-string `lastIndexOf('/')` is exactly what the rest of this
  /// codebase already does for the same question.
  String _basename(String path) => path.substring(path.lastIndexOf('/') + 1);

  /// Builds the exact `whisper-cli` invocation, with every
  /// attacker-influenced path wrapped in [shellQuote] — the remote audio
  /// path and the model path alike, per this feature's security
  /// requirement. Public only through this method's return value in
  /// tests, never logged: see this class's comment on why the transcript,
  /// not the command, is the thing that must never be logged (this
  /// command string carries no dictation content).
  String _transcribeCommand(String remoteAudioPath) {
    return 'whisper-cli '
        '-m ${_modelArgument()} '
        '-f ${shellQuote(remoteAudioPath)} '
        '--prompt ${shellQuote(vocabularyPrompt)} '
        '-nt -np';
  }

  /// The `-m` argument, quoted so the remote shell cannot read anything in
  /// it as syntax.
  ///
  /// An absolute path is quoted whole. A relative one is resolved against
  /// the remote `$HOME`, which means `"\$HOME"` must stay OUTSIDE the
  /// quotes to be expanded at all — single quotes would send the four
  /// literal characters `$HOME` to `whisper-cli`. Double-quoting it still
  /// protects a home directory containing spaces, and the remainder is
  /// single-quoted as usual, so nothing in the configured path can inject.
  String _modelArgument() {
    if (_modelPath.startsWith('/')) return shellQuote(_modelPath);
    return '"\$HOME"/${shellQuote(_modelPath)}';
  }

  Future<void> _deleteRemoteQuietly(String remotePath) async {
    try {
      await _hostRunner.run('rm -f ${shellQuote(remotePath)}');
    } catch (error) {
      // Cleanup failure is logged, never rethrown — the transcription
      // outcome already decided is more important than a delete that
      // failed on the way out, matching SftpUploadService's own discard
      // methods.
      _log.w('Could not delete remote audio: $error');
    }
  }

  Future<void> _deleteLocalQuietly(File file) async {
    try {
      if (await file.exists()) await file.delete();
    } catch (error) {
      _log.w('Could not delete local audio: $error');
    }
  }
}
